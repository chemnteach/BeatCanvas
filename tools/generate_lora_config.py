"""
LoRA Config Generator for ai-toolkit

Generates a ready-to-run YAML config file for ai-toolkit SDXL LoRA training.
Automatically adjusts settings based on available VRAM.

Usage:
    python tools/generate_lora_config.py tiki-bar-interior
    python tools/generate_lora_config.py beach-sunset --vram 12 --steps 3000
    python tools/generate_lora_config.py artist-john --trigger "ohwx" --type character --vram 8

Outputs: config/loras/<name>.yaml ready for: python run.py config/loras/<name>.yaml
"""

